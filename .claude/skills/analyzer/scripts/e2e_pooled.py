"""Corrected pooled e2e table — all overlay corpora, one rule set (Phase 5).

Replaces the retracted 2026-07-12-morning table. Every number is read from
`results/derived/e2e_overlay/` through `e2e_overlay.load_e2e_cells` (the
same single aggregation path the master pivot's `--e2e` flag uses), so
this renderer cannot drift from the analyzer.

Row = (corpus, model, think, task). Columns: no-tools e2e-strict, with-tools
e2e-strict, with-tools tool-verified, and the tool-call-vs-delivered gap
(tool-verified minus e2e-strict, exact cells only). The primary section is
the NEUTRAL prompt bank (v11-13); steered (v14-16) renders in a separate
section marked diagnostic-only per the pre-commitment recorded in
paper_notes_discussions.md 2026-07-12 (no steered no-tools control arm
exists, so steered lift claims are confounded).

Language convention (paper_notes 2026-07-12): run-tagged corpora are
INDEPENDENT RERUN ESTIMATES under full-response storage, never "the
resolved exact value of" a censored cell; corpora are never pooled with
each other — each corpus is its own row block.

Usage:
    python3 e2e_pooled.py [--overlay ROOT] [--out DIR]
Defaults: overlay root results/derived/e2e_overlay (resolved from the repo
root two levels above .claude/), output pooled_e2e_table.{md,csv} next to
the overlay corpora.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

from e2e_overlay import fmt_e2e, load_e2e_cells

REPO = Path(__file__).resolve().parents[4]
DEFAULT_OVERLAY = REPO / "results" / "derived" / "e2e_overlay"

TASK_ORDER = ["solve", "validate_domain", "validate_problem",
              "validate_plan", "simulate"]

# Corpora whose runs are still landing — flagged in the header so a reader
# knows which blocks will change (update this list as they complete).
IN_FLIGHT = {
    "iss024d-e2e-live": "0.8B/35B synced; 4B complete on cluster awaiting "
                        "sync; 9B + gemma still running (2026-07-13)",
}


def _pct(x: float | None) -> str:
    return "—" if x is None else f"{x * 100:.1f}"


def _gap(cell: dict | None) -> str:
    """tool-verified minus e2e-strict, exact e2e cells only."""
    if (cell is None or cell["n"] == 0 or cell["tv_n"] == 0
            or not cell["exact"]):
        return "—"
    tv = cell["tv_ok"] / cell["tv_n"]
    return f"{(tv - cell['low']) * 100:+.1f}"


def _tv(cell: dict | None) -> str:
    if cell is None or cell["tv_n"] == 0:
        return "—"
    return _pct(cell["tv_ok"] / cell["tv_n"])


def build_section(cells: dict, bank: str) -> list[dict]:
    """Rows for one prompt bank ('neut' or 'ster') of one corpus.

    `run` (the dirname run-tag, or the prompt-corpus prefix for frontier
    cells) stays a visible row dimension — differently-tagged cells are
    different corpora and must never collapse into one row.
    """
    keys = sorted({(m, th, tag) for (m, th, _c, tag, _a, _t) in cells})
    rows = []
    for model, think, tag in keys:
        for task in TASK_ORDER:
            nt = cells.get((model, think, "no-tools", tag,
                            f"nt-{bank}", task))
            wt = cells.get((model, think, "tools_all_minimal", tag,
                            f"tl-{bank}", task))
            if nt is None and wt is None:
                continue
            rows.append({
                "model": model, "think": think, "run": tag or "—",
                "task": task, "nt": nt, "wt": wt,
            })
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--overlay", type=Path, default=DEFAULT_OVERLAY)
    ap.add_argument("--out", type=Path, default=None,
                    help="output dir (default: the overlay root)")
    args = ap.parse_args()
    out_dir = args.out or args.overlay
    out_dir.mkdir(parents=True, exist_ok=True)

    corpora = sorted(p.name for p in args.overlay.iterdir() if p.is_dir())
    md = [
        "# Pooled end-to-end table — one rule set over the e2e overlay",
        "",
        "Auto-generated by analyzer `e2e_pooled.py`; do not hand-edit. "
        "Headline metric is `e2e_strict` (D2b=i: empty final turns fail); "
        "grading rules are D7/D7b tolerant extraction "
        "(`tools/e2e_regrade.py`). Cells: point `[lo–hi]` = exact with "
        "Wilson 95% CI; `a–b (ck/n)` = bounds with k of n rows censored "
        "at the response-snapshot cap. gap = tool-verified − e2e-strict, "
        "exact cells only. Corpora are separate blocks and are never "
        "pooled with each other; run-tagged corpora are independent rerun "
        "estimates, not resolutions of older cells.",
        "",
    ]
    for name, why in sorted(IN_FLIGHT.items()):
        if name in corpora:
            md.append(f"**PROVISIONAL:** `{name}` — {why}.")
    md.append("")

    csv_rows = []
    for corpus in corpora:
        cells = load_e2e_cells(corpus, args.overlay)
        if not cells:
            continue
        for bank, title in (("neut", "neutral bank v11-13"),
                            ("ster", "steered bank v14-16 — "
                                     "DIAGNOSTIC-ONLY (no no-tools "
                                     "control arm; pre-commitment "
                                     "2026-07-12)"),
                            ("legacy", "legacy variants (pre-sweep-5)")):
            rows = build_section(cells, bank)
            if not rows:
                continue
            md += [f"## {corpus} — {title}", "",
                   "| model | think | run | task | no-tools e2e "
                   "| tools e2e | tools tool-ver | gap |",
                   "|---|---|---|---|---|---|---|---|"]
            for r in rows:
                md.append(
                    f"| {r['model']} | {r['think']} | {r['run']} "
                    f"| {r['task']} "
                    f"| {fmt_e2e(r['nt'])} | {fmt_e2e(r['wt'])} "
                    f"| {_tv(r['wt'])} | {_gap(r['wt'])} |")
                for side, cell in (("nt", r["nt"]), ("tl", r["wt"])):
                    if cell is None:
                        continue
                    csv_rows.append({
                        "corpus": corpus, "bank": bank,
                        "model": r["model"], "think": r["think"],
                        "run": r["run"],
                        "task": r["task"], "arm": f"{side}-{bank}",
                        "n": cell["n"], "ok_strict": cell["ok"],
                        "censored": cell["cens"],
                        "low": round(cell["low"], 4),
                        "high": round(cell["high"], 4),
                        "ok_b": cell["ok_b"],
                        "tv_ok": cell["tv_ok"], "tv_n": cell["tv_n"],
                    })
            md.append("")

    md_path = out_dir / "pooled_e2e_table.md"
    md_path.write_text("\n".join(md))
    csv_path = out_dir / "pooled_e2e_table.csv"
    with csv_path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(csv_rows[0].keys()))
        w.writeheader()
        w.writerows(csv_rows)
    print(f"wrote {md_path} and {csv_path} ({len(csv_rows)} csv rows)")


if __name__ == "__main__":
    main()
