#!/usr/bin/env python3
"""Qwen3.5-0.8B on validate_domain and validate_problem, main sweep, think=off.

    .venv/bin/python tools/reanalysis/s1_small_model_validation.py

T1 of the Study 1 block covers the three >=9B models only. The paper's
Supporting Analyses also say what the 0.8B model does on the two file-validation
tasks, so this script gives the same figures for it: the unaided rate and the
tool-verified rate under the plain and steered wordings (stored harness grade,
exact on every row; 95% domain-cluster bootstrap as T1, Wilson marked with a
dagger at 0 or 100), the share of trials that call the task's validator, and
the number of trials in which a call to that validator came back with the
plugin's `missing_required_arg` error.

Read-only over results/sweep5v2-live. Writes
tools/reanalysis/out/numbers_s1_small_model_validation.md (spliced into
development/NUMBERS.md by numbers_fill.py).
"""
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from common import NEUT, STER, RESULTS, OUT, load_cell, wilson  # noqa: E402

spec = importlib.util.spec_from_file_location("m02", HERE / "02_cluster_paired_multiplicity.py")
m02 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m02)

MODEL, NAME = "Qwen3_5_0_8B", "Qwen3.5-0.8B"
TASKS = ("validate_domain", "validate_problem")


def cell(rows) -> str:
    b = m02.rate_block(rows, "mech", "mech")
    n = b["n"]
    k = round(b["low"] * n / 100)
    if k in (0, n):
        wl, wh = wilson(k, n)
        return f"{b['low']:.1f} [{100 * wl:.1f}, {100 * wh:.1f}]† ({k}/{n})"
    return f"{b['low']:.1f} [{b['boot_dom'][0]:.1f}, {b['boot_dom'][1]:.1f}] ({k}/{n})"


def call_counts() -> dict:
    """(task, arm) -> trials, trials calling the task's validator, trials with a
    missing_required_arg error from that validator."""
    out = {}
    fp = RESULTS / "sweep5v2-live" / f"slurm_vllm_{MODEL}_off_tools_all_minimal" / "trials.jsonl"
    seen = {}
    with fp.open() as fh:
        for ln in fh:
            try:
                d = json.loads(ln)
            except json.JSONDecodeError:
                continue
            seen[tuple(d["key"])] = d["result"]          # last row wins, as common.load_trials
    for key, r in seen.items():
        task, variant = key[1], key[5]
        if task not in TASKS or r.get("infra_failure"):
            continue
        arm = "plain" if variant in NEUT else "steered"
        calls = [c for c in (r.get("tool_calls") or []) if c.get("name") == task]
        missing = any('"errcode": "missing_required_arg"' in (c.get("result") or "") for c in calls)
        n, called, miss = out.get((task, arm), (0, 0, 0))
        out[(task, arm)] = (n + 1, called + bool(calls), miss + missing)
    return out


def main() -> int:
    nt = load_cell("sweep5v2-live", MODEL, "off", False)
    tl = load_cell("sweep5v2-live", MODEL, "off", True)
    calls = call_counts()
    L = [f"*Generated by `tools/reanalysis/s1_small_model_validation.py`; do not edit between "
         f"the markers, rerun the script. {NAME}, main sweep, think=off. Rates as T1 (stored "
         f"harness grade; 95% domain-cluster bootstrap, counts in brackets). validate_domain "
         f"pools 5 valid trials for each invalid one, so its pooled rate is not a balanced "
         f"accuracy.*", "",
         "| task | unaided | tool-verified, plain | tool-verified, steered | called the "
         "validator, plain / steered | trials with a missing-argument error, plain / steered |",
         "|---|---|---|---|---|---|"]
    for t in TASKS:
        row = [t]
        for rows0, vs in ((nt, NEUT), (tl, NEUT), (tl, STER)):
            row.append(cell([r for r in rows0 if r["task"] == t and r["variant"] in vs]))
        (np_, cp, mp), (ns, cs, ms) = calls[(t, "plain")], calls[(t, "steered")]
        row.append(f"{cp}/{np_} ({100 * cp / np_:.1f}%) / {cs}/{ns} ({100 * cs / ns:.1f}%)")
        row.append(f"{mp}/{np_} / {ms}/{ns}")
        L.append("| " + " | ".join(row) + " |")
    (OUT / "numbers_s1_small_model_validation.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
