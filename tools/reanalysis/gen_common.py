"""Shared helpers for the C3 table generators (`s1_breakdowns_md.py`, `s2_gen_md.py`).

Pure functions only: table rendering (markdown and LaTeX), the generated-block
splice into development/NUMBERS.md, interval formatting and the cost-of-pass
multiplier bootstrap. Nothing here reads results/ or imports the frozen
package, so the tests in tests/test_c3_tables.py run without data.
"""
from __future__ import annotations

import math
import re
from pathlib import Path

import numpy as np

Z95 = 1.959963984540054

MODEL_NAMES = {
    "Qwen3_5_0_8B": "Qwen3.5-0.8B", "Qwen3_5_4B": "Qwen3.5-4B", "Qwen3_5_9B": "Qwen3.5-9B",
    "gemma4_26b-a4b": "Gemma-26B", "qwen3_6_35b": "Qwen3.6-35B", "pooled": "pooled (3 models)",
}


def model_name(tag: str) -> str:
    """Paper name of a model tag; an unknown tag is shown as itself."""
    return MODEL_NAMES.get(tag, tag)


def wilson(k: int, n: int, z: float = Z95) -> tuple[float, float]:
    """Wilson score interval, as fractions."""
    if n == 0:
        return (math.nan, math.nan)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def rate_cell(k: int, n: int, lo: float, hi: float) -> str:
    """'rate [lo, hi]' in percent with a bootstrap interval (lo, hi in percent).
    At a rate of exactly 0 or 100 the bootstrap has zero width, so the Wilson 95%
    interval is shown instead and marked with a dagger (the Study 1 block rule)."""
    if n == 0:
        return "–"
    rate = 100 * k / n
    if k == 0 or k == n:
        wl, wh = wilson(k, n)
        return f"{rate:.1f} [{100 * wl:.1f}, {100 * wh:.1f}]†"
    return f"{rate:.1f} [{lo:.1f}, {hi:.1f}]"


def pct(k: int, n: int) -> str:
    return "–" if n == 0 else f"{100 * k / n:.1f}"


def md_table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


_TEX = [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
        ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}")]
_TEX_SYM = {"†": r"$^{\dagger}$", "‡": r"$^{\ddagger}$", "¶": r"$^{\P}$", "−": "$-$", "–": "--",
            "→": r"$\to$", "×": r"$\times$", "÷": r"$\div$", "≥": r"$\geq$", "≤": r"$\leq$",
            "±": r"$\pm$", "·": r"$\cdot$", "Δ": r"$\Delta$"}


def tex_escape(s: str) -> str:
    s = str(s).replace("**", "")
    s = re.sub(r"`([^`]*)`", r"\1", s)
    for a, b in _TEX:
        if a == "\\":
            s = s.replace(a, "\0")
        else:
            s = s.replace(a, b)
    s = s.replace("\0", _TEX[0][1])
    for a, b in _TEX_SYM.items():
        s = s.replace(a, b)
    return s


def tex_table(headers: list[str], rows: list[list], *, source: str, note: str = "") -> str:
    """A booktabs tabular fragment (no float, no caption: the paper wraps it)."""
    def numeric(col):
        return all(str(r[col]) == "" or str(r[col])[0] in "0123456789-–+" for r in rows)
    spec = "".join("r" if rows and numeric(i) else "l" for i in range(len(headers)))
    out = [f"% generated by {source}; do not edit by hand, rerun the generator",
           *([f"% {ln}" for ln in note.splitlines()] if note else []),
           f"\\begin{{tabular}}{{{spec}}}", r"\toprule",
           " & ".join(tex_escape(h) for h in headers) + r" \\", r"\midrule"]
    out += [" & ".join(tex_escape(c) for c in r) + r" \\" for r in rows]
    out += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(out)


def begin_marker(tag: str) -> str:
    return f"<!-- BEGIN GENERATED: {tag} (do not edit by hand; rerun the generator) -->"


def end_marker(tag: str) -> str:
    return f"<!-- END GENERATED: {tag} -->"


def splice(text: str, tag: str, body: str) -> str:
    """Replace what lies between the BEGIN and END markers of `tag` with `body`.
    Both markers must be present exactly once; nothing outside them changes."""
    b, e = begin_marker(tag), end_marker(tag)
    if text.count(b) != 1 or text.count(e) != 1:
        raise ValueError(f"NUMBERS.md must hold exactly one BEGIN and one END marker for {tag!r}")
    i, j = text.index(b) + len(b), text.index(e)
    if j < i:
        raise ValueError(f"END marker before BEGIN marker for {tag!r}")
    return text[:i] + "\n" + body.rstrip("\n") + "\n" + text[j:]


def write_numbers(path: Path, tag: str, body: str) -> bool:
    """Splice `body` into NUMBERS.md; returns True when the file changed."""
    old = path.read_text()
    new = splice(old, tag, body)
    if new != old:
        path.write_text(new)
    return new != old


def multiplier_boot(ct, st, cn, sn, *, seed: int, b: int) -> dict | None:
    """Cost-of-pass multiplier, tool arm / unaided arm, with a percentile
    domain-cluster bootstrap. Inputs are per-domain arrays in one domain order:
    ct, cn = cost sums (tokens, input + r x output); st, sn = delivered successes.
    The same domain draw is used for both arms. Draws in which either arm has zero
    successes are dropped and counted. Same arithmetic as
    tools/delivered_rerun_secondary.py cost_of_pass (so on the 20-domain set and
    seed 20261002 it reproduces secondary.json exactly)."""
    ct, st, cn, sn = (np.asarray(x, float) for x in (ct, st, cn, sn))
    if st.sum() == 0 or sn.sum() == 0:
        return None
    k = len(ct)
    est = (ct.sum() / st.sum()) / (cn.sum() / sn.sum())
    rng = np.random.default_rng(seed)
    draws = rng.integers(0, k, size=(b, k))
    a, c = st[draws].sum(1), sn[draws].sum(1)
    valid = (a > 0) & (c > 0)
    vals = (ct[draws].sum(1)[valid] / a[valid]) / (cn[draws].sum(1)[valid] / c[valid])
    lo, hi = np.quantile(vals, [0.025, 0.975])
    return {"est": float(est), "lo": float(lo), "hi": float(hi),
            "draws_with_zero_successes": int((~valid).sum()), "k": k}


def mult_cell(m: dict | None) -> str:
    if m is None:
        return "–"
    nz = m["draws_with_zero_successes"]
    z = f" ({nz} draw{'s' if nz != 1 else ''} dropped)" if nz else ""
    return f"{m['est']:.2f} [{m['lo']:.2f}, {m['hi']:.2f}]{z}"
